def _wait_for(predicate, *, timeout: float = 10) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(0.05)
    pytest.fail("Timed out waiting for the test executable or update helper")


@pytest.fixture(scope="module")
def tiny_executables(tmp_path_factory):
    if os.name != "nt":
        pytest.skip("Real update replacement requires Windows")
    windows = Path(os.environ.get("SystemRoot", r"C:\Windows"))
    candidates = [
        windows / "Microsoft.NET" / framework / "v4.0.30319" / "csc.exe"
        for framework in ("Framework64", "Framework")
    ]
    compiler = next((path for path in candidates if path.is_file()), None)
    if compiler is None:
        pytest.skip("The Windows .NET Framework C# compiler is unavailable")
    directory = tmp_path_factory.mktemp("update_test_executables")
    programs = {
        "old": """
            File.WriteAllText(path + ".ready", "old process running");
            DateTime deadline = DateTime.UtcNow.AddSeconds(45);
            while (!File.Exists(path + ".stop") && DateTime.UtcNow < deadline)
                System.Threading.Thread.Sleep(30);
        """,
        "new": """
            File.WriteAllText(path + ".started", "updated|"
                + Environment.GetEnvironmentVariable("PYINSTALLER_RESET_ENVIRONMENT")
                + "|" + (Environment.GetEnvironmentVariable("_PYI_APPLICATION_HOME_DIR") ?? "unset"));
        """,
    }
    outputs = []
    for name, body in programs.items():
        source = directory / (name + ".cs")
        output = directory / (name + ".exe")
        source.write_text(
            "using System; using System.IO; class Program { static void Main() {"
            "string path = System.Reflection.Assembly.GetExecutingAssembly().Location;"
            + body + "} }",
            encoding="utf-8",
        )
        # No console window is needed for these noninteractive test programs.
        result = subprocess.run(
            [str(compiler), "/nologo", "/target:winexe", "/out:" + str(output), str(source)],
            capture_output=True, timeout=30,
            creationflags=subprocess.CREATE_NO_WINDOW,
        )
        assert result.returncode == 0, result.stdout + result.stderr
        outputs.append(output)
    return tuple(outputs)


@dataclass
class ReplacementCase:
    current: Path
    downloaded: Path
    backup: Path
    log: Path
    ready: Path
    script: Path
    old_bytes: bytes
    new_bytes: bytes


@pytest.fixture
def replacement_case(tmp_path, tiny_executables):
    directory = tmp_path / "中文 路径's update"
    directory.mkdir()
    current = directory / "旧 软件'original.exe"
    downloaded = directory / "新 软件'download.exe"
    shutil.copyfile(tiny_executables[0], current)
    shutil.copyfile(tiny_executables[1], downloaded)
    return ReplacementCase(
        current=current, downloaded=downloaded,
        backup=current.with_name(current.name + ".old"),
        log=directory / "更新 日志'log.txt",
        ready=directory / "更新 就绪'ready.txt",
        script=directory / "应用 更新'helper.ps1",
        old_bytes=current.read_bytes(), new_bytes=downloaded.read_bytes(),
    )


@contextmanager
def _running_old_executable(case):
    process = subprocess.Popen(
        [str(case.current)], cwd=case.current.parent,
        creationflags=subprocess.CREATE_NO_WINDOW,
    )
    try:
        _wait_for(lambda: Path(str(case.current) + ".ready").exists())
        yield process
    finally:
        Path(str(case.current) + ".stop").touch()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=5)


@contextmanager
def _running_helper(case, old_pid, *, suppress_failure_ui=False, script_transform=None):
    script = updater._replacement_script_text(
        case.current, case.downloaded, case.backup, case.log, old_pid, case.ready,
    )
    if suppress_failure_ui:
        # Only replace failure notifications, leaving every filesystem and
        # process replacement operation exactly as generated by production.
        script = re.sub(
            r'(?m)^([ \t]*)Show-UpdateMessage .*$',
            r'\1Write-UpdateLog "test suppressed failure dialog"', script,
        )
    if script_transform is not None:
        script = script_transform(script)
    case.script.write_text(script, encoding="utf-8-sig")
    process = subprocess.Popen(
        [updater._powershell_executable(), "-NoLogo", "-NoProfile", "-NonInteractive",
         "-ExecutionPolicy", "Bypass", "-File", str(case.script)],
        cwd=case.script.parent, stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        creationflags=subprocess.CREATE_NO_WINDOW,
        env={**updater._windows_update_script_environment(),
             "_PYI_APPLICATION_HOME_DIR": "stale-test-environment"},
    )
    try:
        _wait_for(case.ready.exists)
        yield process
    finally:
        if process.poll() is None:
            process.kill()
        process.communicate(timeout=5)


@contextmanager
def _exclusive_file(path):
    """Hold a genuine Windows sharing lock so Copy-Item cannot write a file."""
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    create = kernel.CreateFileW
    create.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                       wintypes.LPVOID, wintypes.DWORD, wintypes.DWORD, wintypes.HANDLE]
    create.restype = wintypes.HANDLE
    close = kernel.CloseHandle
    close.argtypes = [wintypes.HANDLE]
    close.restype = wintypes.BOOL
    handle = create(str(path), 0xC0000000, 0, None, 2, 0x80, None)
    if handle == wintypes.HANDLE(-1).value:
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        yield
    finally:
        close(handle)


def test_replacement_waits_preserves_backup_and_restarts_automatically(replacement_case):
    case = replacement_case
    with _running_old_executable(case) as old, _running_helper(case, old.pid) as helper:
        # Check real process/file state while the old program is running.
        # Diagnostic logging is best-effort and is not a synchronization API.
        time.sleep(0.3)
        assert helper.poll() is None
        assert old.poll() is None
        assert case.current.read_bytes() == case.old_bytes
        assert not case.backup.exists()
        Path(str(case.current) + ".stop").touch()
        old.wait(timeout=5)
        output, _ = helper.communicate(timeout=20)
        assert helper.returncode == 0, output
    marker = Path(str(case.current) + ".started")
    _wait_for(marker.exists)
    assert case.current.read_bytes() == case.new_bytes
    assert case.backup.read_bytes() == case.old_bytes
    assert marker.read_text() == "updated|1|unset"
    assert not Path(str(case.downloaded) + ".started").exists()


def test_replacement_handles_old_process_exiting_between_lookup_and_wait(replacement_case):
    case = replacement_case

    def exit_old_process_after_lookup(script):
        lookup = "    $process = Get-Process -Id $OldProcessId -ErrorAction SilentlyContinue"
        assert script.count(lookup) == 1, "Cannot locate process lookup for race synchronization"
        synchronization = """
    if (!$process) { throw "test old process was not running at lookup" }
    Set-Content -LiteralPath ($OldPath + ".stop") -Value "exit for race test"
    if (!$process.WaitForExit(5000)) { throw "test old process did not exit" }
    Set-Content -LiteralPath ($OldPath + ".exited-before-wait") -Value $process.HasExited
"""
        # Actually exit the old process before executing production Wait-Process;
        # no waiting, replacement or restart operation is mocked or removed.
        return script.replace(lookup, lookup + synchronization, 1)

    with _running_old_executable(case) as old, _running_helper(
        case, old.pid, script_transform=exit_old_process_after_lookup,
    ) as helper:
        output, _ = helper.communicate(timeout=20)
        assert helper.returncode == 0, output + case.log.read_bytes()
        assert old.wait(timeout=5) == 0
    assert Path(str(case.current) + ".exited-before-wait").read_text().strip() == "True"
    _wait_for(lambda: Path(str(case.current) + ".started").exists())
    assert case.current.read_bytes() == case.new_bytes
    assert case.backup.read_bytes() == case.old_bytes


@pytest.mark.parametrize("failure", ["missing_download", "copy_locked"])
def test_replacement_failure_keeps_original_executable(replacement_case, failure):
    case = replacement_case
    if failure == "missing_download":
        case.downloaded.unlink()
    with _running_old_executable(case) as old, _running_helper(
        case, old.pid, suppress_failure_ui=True,
    ) as helper:
        if failure == "copy_locked":
            with _exclusive_file(Path(str(case.current) + f".{helper.pid}.updating")):
                Path(str(case.current) + ".stop").touch()
                old.wait(timeout=5)
                helper.communicate(timeout=20)
        else:
            Path(str(case.current) + ".stop").touch()
            old.wait(timeout=5)
            helper.communicate(timeout=20)
    failure_log = case.log.read_text(encoding="utf-8-sig")
    assert "apply update failed:" in failure_log
    if failure == "copy_locked":
        assert ".updating" in failure_log  # Failure reached the genuinely locked staging file.
    assert case.current.read_bytes() == case.old_bytes
    assert not case.backup.exists()
    assert not Path(str(case.current) + ".started").exists()


@pytest.mark.parametrize("polluted_module_path", [False, True])
def test_real_launcher_acknowledges_helper_then_updates_and_restarts(
    replacement_case, monkeypatch, polluted_module_path,
):
    """Use production Popen flags: DETACHED_PROCESS once silently skipped the script."""
    case = replacement_case
    real_popen = subprocess.Popen
    helpers = []

    if polluted_module_path:
        modules = case.script.parent / "inherited modules"
        shadow = modules / "Microsoft.PowerShell.Utility"
        shadow.mkdir(parents=True)
        (shadow / "Shadow.psm1").write_text(
            "function Get-FileHash { throw 'test inherited incompatible utility module' }\n"
            "Export-ModuleMember -Function Get-FileHash\n", encoding="utf-8",
        )
        (shadow / "Microsoft.PowerShell.Utility.psd1").write_text(
            "@{ ModuleVersion='99.0.0'; RootModule='Shadow.psm1'; "
            "FunctionsToExport=@('Get-FileHash'); CmdletsToExport=@(); AliasesToExport=@() }",
            encoding="utf-8",
        )
        inherited_modules = str(modules) + os.pathsep + os.environ.get("PSMODULEPATH", "")
        monkeypatch.setenv("PSMODULEPATH", inherited_modules)
        # Establish that this inherited environment actually breaks Windows
        # PowerShell before requiring the production launcher to recover.
        probe = subprocess.run(
            [updater._powershell_executable(), "-NoProfile", "-NonInteractive", "-Command",
             "$ErrorActionPreference='Stop'; Get-FileHash -LiteralPath "
             + updater._ps_single_quoted(str(case.downloaded))],
            capture_output=True, timeout=10, creationflags=subprocess.CREATE_NO_WINDOW,
        )
        assert probe.returncode != 0
        assert b"test inherited incompatible utility module" in probe.stderr

    def record_helper(*args, **kwargs):
        process = real_popen(*args, **kwargs)
        helpers.append(process)
        return process

    with _running_old_executable(case) as old:
        try:
            with monkeypatch.context() as patch:
                patch.setattr(updater, "_download_dir", lambda: case.script.parent)
                patch.setattr(updater.sys, "executable", str(case.current))
                patch.setattr(updater.os, "getpid", lambda: old.pid)
                patch.setattr(updater.subprocess, "Popen", record_helper)
                updater._launch_replacement_script(case.downloaded)
            assert len(helpers) == 1
            assert helpers[0].poll() is None
            assert old.poll() is None
            assert case.current.read_bytes() == case.old_bytes
            Path(str(case.current) + ".stop").touch()
            old.wait(timeout=5)
            assert helpers[0].wait(timeout=20) == 0
        finally:
            for helper in helpers:
                if helper.poll() is None:
                    helper.kill()
                helper.wait(timeout=5)
    _wait_for(lambda: Path(str(case.current) + ".started").exists())
    assert case.current.read_bytes() == case.new_bytes
    assert case.backup.read_bytes() == case.old_bytes


