@pytest.mark.parametrize("failure", ["directory_creation", "script_write"])
def test_launcher_wraps_preparation_errors_without_starting_helper(tmp_path, monkeypatch, failure):
    script_directory = tmp_path / "helper files"
    fixed_uuid = updater.uuid.UUID(int=1)
    if failure == "directory_creation":
        script_directory.write_bytes(b"A file prevents creating the helper directory")
    else:
        script_directory.mkdir()
        script_path = script_directory / f"apply_update_{os.getpid()}_{fixed_uuid.hex}.ps1"
        script_path.mkdir()  # A directory prevents writing the script file.
    monkeypatch.setattr(updater, "_download_dir", lambda: script_directory)
    monkeypatch.setattr(updater.sys, "executable", str(tmp_path / "test-old.exe"))
    monkeypatch.setattr(updater.uuid, "uuid4", lambda: fixed_uuid)
    popen_calls = []

    def unexpected_start(*args, **kwargs):
        popen_calls.append((args, kwargs))
        raise AssertionError("The helper must not start after preparation fails")

    monkeypatch.setattr(updater.subprocess, "Popen", unexpected_start)
    with pytest.raises(updater.UpdateDownloadError) as caught:
        updater._launch_replacement_script(tmp_path / "test-new.exe")
    assert isinstance(caught.value.__cause__, OSError)
    assert not popen_calls


