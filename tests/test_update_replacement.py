def test_launcher_terminates_helper_that_never_acknowledges(tmp_path, monkeypatch):
    class UnresponsiveHelper:
        pid = 987654
        returncode = None
        terminated = False

        def poll(self):
            return self.returncode

        def terminate(self):
            self.terminated = True
            self.returncode = -1

        def wait(self, timeout):
            assert self.terminated
            return self.returncode

    helper = UnresponsiveHelper()
    clock = iter((0.0, 16.0))
    with monkeypatch.context() as patch:
        patch.setattr(updater, "_download_dir", lambda: tmp_path)
        patch.setattr(updater.sys, "executable", str(tmp_path / "test-old.exe"))
        patch.setattr(updater.subprocess, "Popen", lambda *args, **kwargs: helper)
        patch.setattr(updater.time, "monotonic", lambda: next(clock))
        with pytest.raises(updater.UpdateDownloadError):
            updater._launch_replacement_script(tmp_path / "test-new.exe")
    assert helper.terminated
